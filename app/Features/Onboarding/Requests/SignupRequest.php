<?php

namespace App\Features\Onboarding\Requests;

use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Support\Str;

class SignupRequest extends FormRequest
{
    public function authorize(): bool
    {
        return true;
    }

    protected function prepareForValidation(): void
    {
        $this->merge(['email' => Str::lower(trim((string) $this->input('email')))]);
    }

    public function rules(): array
    {
        return [
            'company_name' => ['required', 'string', 'max:255'],
            'name' => ['required', 'string', 'max:255'],
            // Unique across the whole platform (TenantRule): one account per email.
            'email' => ['required', 'string', 'email', 'max:255', 'unique:users,email'],
            'password' => ['required', 'string', 'min:8', 'confirmed'],
        ];
    }

    public function messages(): array
    {
        return [
            'email.unique' => 'This email address already has an account. Sign in instead, or use a different email.',
        ];
    }
}
